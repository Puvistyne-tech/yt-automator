from __future__ import annotations

from typing import Any

from pydantic import Field

from autotube.infrastructure.providers.ffmpeg_args import X264Options

SIZE_STEP = 64
DEFAULT_PACK = "~/.autotube/models/reverie-studio__ltx-2.5-mlx-q4-distilled"
DEFAULT_NEGATIVE = "text, captions, watermark, blurry, distorted, extra limbs"


def size_field(default: int, title: str) -> Any:
    return Field(
        default=default,
        ge=SIZE_STEP,
        multiple_of=SIZE_STEP,
        title=title,
        description="Pixels generated by the model, a multiple of 64.",
    )


class LtxOptions(X264Options):
    binary: str = Field(
        default="ltx-2-mlx", min_length=1, title="Command", description="ltx-2-mlx executable."
    )
    model_dir: str = Field(
        default=DEFAULT_PACK,
        min_length=1,
        title="Model folder",
        description="Folder holding the LTX MLX weights pack; ~ means your home folder.",
    )
    distilled: bool = Field(
        default=True,
        title="Distilled pipeline",
        description="Run the fast distilled pipeline; turn off for a full (non-distilled) pack.",
    )
    text_encoder: str = Field(
        default="",
        title="Text encoder",
        description="Gemma text encoder for packs without one; empty uses the pack's own.",
    )
    negative_prompt: str = Field(
        default=DEFAULT_NEGATIVE,
        title="Negative prompt",
        description="What the clip must avoid. Used only with NAG guidance.",
    )
    use_nag: bool = Field(
        default=True,
        title="NAG guidance",
        description="Apply normalized attention guidance so the negative prompt takes effect.",
    )
    seed: int = Field(default=42, ge=0, title="Seed", description="Random seed for every segment.")
    frame_rate: int = Field(
        default=24,
        ge=1,
        le=60,
        title="Model frame rate",
        description="Frames per second generated.",
    )
    landscape_width: int = size_field(704, "Landscape width")
    landscape_height: int = size_field(384, "Landscape height")
    portrait_width: int = size_field(384, "Portrait width")
    portrait_height: int = size_field(704, "Portrait height")
    max_segment_seconds: float = Field(
        default=3.0,
        gt=0,
        le=20.0,
        title="Longest segment",
        description="Seconds per generated segment; longer clips are chained from the last frame.",
    )
    image_strength: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        title="Image strength",
        description="How strictly the first frame follows the starting picture.",
    )
    hf_home: str = Field(
        default="~/.autotube/hf",
        title="Hugging Face cache",
        description=(
            "HF_HOME folder for cached models (~ means your home folder); "
            "empty keeps the environment's."
        ),
    )
    hf_offline: bool = Field(
        default=True,
        title="Offline cache only",
        description="Set HF_HUB_OFFLINE so nothing is downloaded during a run.",
    )
    timeout_seconds: float = Field(
        default=1200.0, gt=0, title="Timeout", description="Seconds allowed for one segment."
    )
